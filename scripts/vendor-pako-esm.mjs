#!/usr/bin/env node
// Derive a browser-native ESM module from pako 1.0.11's published UMD without
// asking a bundler to interpret its environment-detecting wrapper. The codec
// factory body stays byte-for-byte identical to the locked upstream artifact;
// only that outer wrapper is replaced with static named ESM exports.

import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const VENDOR = join(ROOT, 'extension', 'vendor', 'pako');
const INPUT = join(VENDOR, 'pako.min.js');
const OUTPUT = join(VENDOR, 'pako.esm.js');
const UPSTREAM_SHA256 = '29cfa0542b9864b6640cfdcc8f15b184db6431b532db2702a3ce97e5f2a7fc1c';
const FACTORY_MARKER = '}(function(){return ';

const upstreamBytes = await readFile(INPUT);
const actualHash = createHash('sha256').update(upstreamBytes).digest('hex');
if (actualHash !== UPSTREAM_SHA256) {
  throw new Error(`refusing to transform unreviewed pako bytes: ${actualHash}`);
}

const upstream = upstreamBytes.toString('utf8');
const marker = upstream.indexOf(FACTORY_MARKER);
if (marker < 0 || upstream.indexOf(FACTORY_MARKER, marker + 1) >= 0 || !upstream.endsWith('});\n')) {
  throw new Error('pako UMD wrapper shape changed; review the transform before updating it');
}

const factoryStatement = upstream.slice(marker + 1).trimEnd();
if (!factoryStatement.endsWith(');')) {
  throw new Error('pako factory terminator changed; review the transform before updating it');
}
const factoryExpression = factoryStatement.slice(0, -1);
const generated = [
  '// Generated by scripts/vendor-pako-esm.mjs from byte-locked pako.min.js.',
  '// Do not edit: regenerate it and update SOURCE.txt + vendor.lock.json together.',
  `const pako=${factoryExpression}();`,
  "if (typeof pako.Deflate !== 'function' || typeof pako.Inflate !== 'function') throw new Error('vendored pako bundle failed to initialize');",
  'export const Deflate=pako.Deflate;',
  'export const Inflate=pako.Inflate;',
  '',
].join('\n');

await writeFile(OUTPUT, generated);
console.log(`wrote ${OUTPUT} (${Buffer.byteLength(generated)} bytes)`);
